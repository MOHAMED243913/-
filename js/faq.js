function renderFAQ() {
  const wrap = document.getElementById('faqWrap');
  if (!wrap) return;
  wrap.innerHTML = FAQ_DATA.map((cat, ci) => `
    <div class="faq-category">
      <div class="faq-category-title"><span class="num">${ci + 1}</span> ${cat.category}</div>
      ${cat.items.map((item, ii) => `
        <div class="faq-item" id="faq-${ci}-${ii}">
          <button class="faq-question">
            <span>${item.q}</span>
            <span class="chevron">${Icon('chevronDown')}</span>
          </button>
          <div class="faq-answer"><p>${item.a}</p></div>
        </div>`).join('')}
    </div>`).join('');

  wrap.querySelectorAll('.faq-item').forEach(item => {
    item.querySelector('.faq-question').addEventListener('click', () => {
      item.classList.toggle('open');
    });
  });
}

document.addEventListener('DOMContentLoaded', renderFAQ);
